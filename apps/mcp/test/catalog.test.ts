import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { TOOLS } from '../src/mcp/server';
import { SERVER_VERSION } from '../src/version';
import { connectClient, type Harness, type ListedTool, seedBasics, startHarness } from './harness';
import { isObject } from './helpers';

/*
 * The docs site (apps/mcp-docs) renders its tool reference from
 * apps/mcp-docs/lib/tool-catalog.json. This test rebuilds that catalogue from
 * the live `tools/list` answer and fails when the committed file drifts.
 * Regenerate with: UPDATE_TOOL_CATALOG=1 pnpm --filter @openlinear/mcp test
 */
const CATALOG_PATH = resolve(import.meta.dirname, '../../mcp-docs/lib/tool-catalog.json');

type Schema = Record<string, unknown>;

function bound(value: unknown): number | undefined {
  // zod emits ±(2^53 - 1) for unbounded integers; treat those as no bound.
  return typeof value === 'number' && Math.abs(value) < Number.MAX_SAFE_INTEGER ? value : undefined;
}

function range(schema: Schema, min: string, max: string): string {
  const low = bound(schema[min]);
  const high = bound(schema[max]);
  if (low !== undefined && high !== undefined) return ` ${low}–${high}`;
  if (high !== undefined) return ` ≤ ${high}`;
  if (low !== undefined && low > 0) return ` ≥ ${low}`;
  return '';
}

/** A short human type for a JSON Schema node, e.g. `uuid`, `string 1–500`, `todo | done`. */
function describeType(schema: unknown): string {
  if (!isObject(schema)) return 'any';
  const variants = Array.isArray(schema.anyOf) ? schema.anyOf : undefined;
  if (variants) return variants.map(describeType).join(' | ');
  if (Array.isArray(schema.enum)) return schema.enum.map(String).join(' | ');
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  switch (schema.type) {
    case 'string':
      if (schema.format === 'uuid') return 'uuid';
      if (schema.format === 'date-time') return 'ISO date-time';
      return `string${range(schema, 'minLength', 'maxLength')}`;
    case 'integer':
    case 'number':
      return `${schema.type}${range(schema, 'minimum', 'maximum')}`;
    case 'array': {
      const item = describeType(schema.items);
      const wrapped = item.includes(' ') ? `(${item})` : item;
      return `${wrapped}[]${range(schema, 'minItems', 'maxItems')}`;
    }
    case 'object':
      return 'object';
    case 'null':
      return 'null';
    case 'boolean':
      return 'boolean';
    default:
      return 'any';
  }
}

function inputsOf(tool: ListedTool) {
  const properties = isObject(tool.inputSchema.properties) ? tool.inputSchema.properties : {};
  const required = Array.isArray(tool.inputSchema.required) ? tool.inputSchema.required : [];
  return Object.entries(properties).map(([name, schema]) => ({
    name,
    type: describeType(schema),
    required: required.includes(name),
    ...(isObject(schema) && schema.default !== undefined ? { default: schema.default } : {}),
    description: isObject(schema) && typeof schema.description === 'string' ? schema.description : '',
  }));
}

describe('tool catalogue for the docs site', () => {
  let harness: Harness;
  let tools: ListedTool[];

  beforeAll(async () => {
    harness = await startHarness();
    const client = await connectClient('v2-modern', harness.mcpUrl, seedBasics(harness.api).token);
    tools = await client.listTools();
    await client.close();
  });
  afterAll(async () => harness.stop());

  it('matches apps/mcp-docs/lib/tool-catalog.json', () => {
    const catalog = {
      $comment: 'Generated by apps/mcp/test/catalog.test.ts from the live tools/list. Do not edit by hand.',
      serverVersion: SERVER_VERSION,
      endpoint: 'https://mcp.openlinear.tech/mcp',
      tools: tools.map((tool) => {
        const spec = TOOLS.find((candidate) => candidate.name === tool.name);
        return {
          name: tool.name,
          title: tool.title ?? tool.name,
          description: tool.description ?? '',
          annotations: {
            readOnlyHint: tool.annotations?.readOnlyHint === true,
            destructiveHint: tool.annotations?.destructiveHint === true,
            idempotentHint: tool.annotations?.idempotentHint === true,
            openWorldHint: tool.annotations?.openWorldHint === true,
          },
          scopes: spec ? [...spec.scopes] : [],
          inputs: inputsOf(tool),
        };
      }),
    };
    const serialized = `${JSON.stringify(catalog, null, 2)}\n`;
    if (process.env.UPDATE_TOOL_CATALOG === '1') writeFileSync(CATALOG_PATH, serialized);
    expect(readFileSync(CATALOG_PATH, 'utf8')).toBe(serialized);
  });

  it('describes JSON Schema types compactly', () => {
    expect(describeType({ type: 'string', format: 'uuid' })).toBe('uuid');
    expect(describeType({ type: 'string', minLength: 1, maxLength: 500 })).toBe('string 1–500');
    expect(describeType({ anyOf: [{ type: 'string', format: 'uuid' }, { type: 'null' }] })).toBe('uuid | null');
    expect(describeType({ type: 'array', items: { type: 'string', format: 'uuid' }, maxItems: 20 })).toBe('uuid[] ≤ 20');
    expect(describeType({ type: 'integer', minimum: 1, maximum: 100 })).toBe('integer 1–100');
    expect(describeType({ type: 'integer', minimum: 0, maximum: Number.MAX_SAFE_INTEGER })).toBe('integer');
    expect(describeType({ type: 'string', enum: ['todo', 'done'] })).toBe('todo | done');
  });
});
